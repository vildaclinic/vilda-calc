import { expect, test } from '../support/test-czas.mjs';
import { openCalculator, applyAcr, applyU25, saveVisible, memory, configureMemory } from '../support/klirens-patient-record.mjs';

test.use({ chwila: '2026-10-25T12:00:00Z' });
const renal = page => page.locator('.vilda-lab-hist-panel[data-panel="renal"] .vilda-clcr-history');
const field = (page, id) => page.locator(`[data-clcr-edit-field="${id}"]`);
const point = (page, id) => renal(page).locator(`.vilda-clcr-point[data-note-id="${id}"]`);

async function storedPoint(page, noteId) {
  const notes = (await memory(page)).notes;
  return page.evaluate(({ saved, id }) => window.ClcrSavedResults.projectPatientNotes(saved).measurements.find(record => record.noteId === id), { saved: notes, id: noteId });
}

async function createHistory(page) {
  const ids = {};
  for (const [key, value, date] of [['normal', '13.6', '2026-10-20'], ['acr', '45', '2026-10-25'], ['sibling', '255.9', '2026-10-25']]) {
    await applyAcr(page, value); ids[key] = (await saveVisible(page, date))[0].id;
  }
  await applyU25(page, '0.600'); ids.u25 = (await saveVisible(page, '2026-10-20'))[0].id;
  await applyU25(page, '0.515'); ids.u25Other = (await saveVisible(page, '2026-10-25'))[0].id;
  await page.locator('#clcrOpenBadaniaBtn').click();
  await expect(renal(page).locator('tr[data-note-id]')).toHaveCount(5);
  return ids;
}

async function openDetails(page, id, keyboard = false) {
  if (keyboard) { await point(page, id).focus(); await point(page, id).press('Enter'); }
  else await point(page, id).click();
  await expect(page.locator('#detailsDialog')).toBeVisible();
  await expect(page.locator('#calculationDetails')).toHaveAttribute('data-note-id', id);
}
const edit = page => page.locator('#editMeasurement').click();
async function commit(page) {
  await page.locator('#saveEditedMeasurement').click();
  await expect(page.locator('#editDialog')).toBeHidden();
  await expect(page.locator('#detailsDialog')).toBeVisible();
}
async function closeDetails(page) { await page.locator('#detailsDialog').getByRole('button', { name: 'Zamknij', exact: true }).click(); }

// New historical calculations are generated by the real form+writer. No fake
// prototype snapshot or copied clinical formula enters the production reader.
test('ACR editing replaces the same note and full assessment, respects historical age and clears unsupported norms', async ({ page }) => {
  await openCalculator(page);
  const ids = await createHistory(page);
  const before = await memory(page);
  await openDetails(page, ids.acr, true);
  await edit(page);
  await expect(field(page, 'U_Alb')).toHaveValue('45');
  await field(page, 'U_Alb').fill('301');
  await page.locator('#editDialog').getByRole('button', { name: 'Anuluj', exact: true }).first().click();
  expect((await memory(page)).notes).toEqual(before.notes);
  await edit(page);
  await field(page, 'Ucr_spot').fill('0');
  await page.locator('#saveEditedMeasurement').click();
  await expect(page.locator('#editDialog')).toBeVisible();
  await expect(page.locator('#editError')).toBeVisible();
  expect((await memory(page)).notes).toEqual(before.notes);
  await field(page, 'Ucr_spot').fill('100');
  await field(page, 'U_Alb').fill('13.6');
  await page.locator('#editDate').fill('2025-10-21');
  await expect(page.locator('#editHistoricalSummary')).toContainText('10');
  await commit(page);
  await expect.poll(() => storedPoint(page, ids.acr)).toMatchObject({ noteId: ids.acr, valueNum: 13.6, category: 'A1', tone: 'success', norm: '<30 mg/g', dateISO: '2025-10-21' });
  const after = await memory(page);
  expect(after.notes).toHaveLength(5);
  expect(after.notes.map(note => note.id).sort()).toEqual(before.notes.map(note => note.id).sort());
  expect(after.updates).toHaveLength(1);
  expect(after.updates[0]).toMatchObject({ id: ids.acr, patientId: before.notes.find(note => note.id === ids.acr).patientId, baseRev: 1 });
  await expect(page.locator('#calculationDetails')).toContainText('13,6');
  await expect(page.locator('#calculationDetails')).not.toContainText('Podwyższony wynik');
  await edit(page);
  await page.locator('#changeHistoricalContext').click();
  await page.locator('#editAge').fill('1.5');
  await commit(page);
  await expect.poll(() => storedPoint(page, ids.acr)).toMatchObject({ valueNum: 13.6, category: null, tone: 'neutral', norm: '' });
  await expect(page.locator('#calculationDetails')).not.toContainText('<30');
  await closeDetails(page);
  await expect(renal(page).locator(`tr[data-note-id="${ids.acr}"] .vilda-clcr-row-reference`)).toHaveText('Brak zapisanej normy');
  await expect(point(page, ids.acr)).toHaveClass(/tone-neutral/);
  const sameGroup = point(page, ids.acr).locator('xpath=ancestor::section[contains(@class,"vilda-clcr-measurement-group")]');
  await expect(sameGroup.locator('.vilda-clcr-norm-band')).toHaveCount(0);
  await page.evaluate(() => window.VildaAuthUI.hide());
  await page.locator('#clcrOpenHistoryBtn').click();
  await expect(page.locator(`#clcrPatientCard tr[data-note-id="${ids.acr}"] .vilda-clcr-row-reference`)).toHaveText('Brak zapisanej normy');
  expect((await memory(page)).notes.find(note => note.id === ids.sibling)).toEqual(before.notes.find(note => note.id === ids.sibling));
  expect((await memory(page)).originalsLocked).toBe(true);
});

test('U25 editing uses actual engines, retains exact rounding boundary and removes G/90 before age2', async ({ page }) => {
  await openCalculator(page);
  const ids = await createHistory(page);
  await openDetails(page, ids.u25);
  await edit(page);
  await field(page, 'Scr').fill('0.515');
  await commit(page);
  await expect.poll(async () => (await storedPoint(page, ids.u25)).valueNum).toBeCloseTo(96.5843906782418, 10);
  expect(await storedPoint(page, ids.u25)).toMatchObject({ noteId: ids.u25, category: 'G1', tone: 'success', norm: '≥90 mL/min/1,73 m²' });
  await edit(page);
  await field(page, 'Scr').fill('0.5545');
  await commit(page);
  await expect.poll(async () => (await storedPoint(page, ids.u25)).valueNum).toBeCloseTo(89.70416807807851, 10);
  expect(await storedPoint(page, ids.u25)).toMatchObject({ category: 'G2', tone: 'warning' });
  await expect(page.locator('#calculationDetails')).toContainText('Przed zaokrągleniem');
  await expect(page.locator('#calculationDetails')).toContainText('<90');
  await edit(page);
  await page.locator('#changeHistoricalContext').click();
  await page.locator('#editAge').fill('0');
  await page.locator('#saveEditedMeasurement').click();
  await expect(page.locator('#editError')).toBeVisible();
  expect((await storedPoint(page, ids.u25)).category).toBe('G2');
  await page.locator('#editAge').fill('1.5');
  await field(page, 'height').fill('85');
  await field(page, 'Scr').fill('0.4');
  await commit(page);
  await expect.poll(async () => (await storedPoint(page, ids.u25)).valueNum).toBeCloseTo(70.55544724174037, 10);
  expect(await storedPoint(page, ids.u25)).toMatchObject({ category: null, tone: 'neutral', norm: '' });
  await expect(page.locator('#calculationDetails')).not.toContainText('≥90');
  expect((await memory(page)).notes).toHaveLength(5);
  expect((await memory(page)).saves).toHaveLength(5);
});

test('delete targets one ID, cancel preserves same-day siblings and the last note gives safe empty views', async ({ page }) => {
  await openCalculator(page);
  await applyAcr(page, '45');
  const [first] = await saveVisible(page);
  await applyAcr(page, '255.9');
  const [sibling] = await saveVisible(page);
  await page.locator('#clcrOpenBadaniaBtn').click();
  await openDetails(page, first.id);
  await page.locator('#deleteMeasurement').click();
  await expect(page.locator('#deleteSummary')).toContainText('45');
  await expect(page.locator('#deleteSummary')).toContainText('25.10');
  await page.locator('#deleteDialog').getByRole('button', { name: 'Anuluj', exact: true }).click();
  expect((await memory(page)).notes).toHaveLength(2);
  await page.locator('#deleteMeasurement').click();
  await page.locator('#confirmDeleteMeasurement').focus();
  await page.locator('#confirmDeleteMeasurement').press('Space');
  await expect(page.locator('#detailsDialog')).toBeHidden();
  await expect(renal(page).locator(`tr[data-note-id="${first.id}"]`)).toHaveCount(0);
  await expect(point(page, first.id)).toHaveCount(0);
  expect((await memory(page)).notes).toEqual([sibling]);
  await openDetails(page, sibling.id);
  await page.locator('#deleteMeasurement').click();
  await page.locator('#confirmDeleteMeasurement').click();
  await expect(renal(page).locator('tr[data-note-id], .vilda-clcr-point')).toHaveCount(0);
  expect((await memory(page)).notes).toHaveLength(0);
  await page.evaluate(() => window.VildaAuthUI.hide());
  await expect(page.locator('#clcrVisitSaveBtn')).toBeEnabled();
  await expect(page.locator('#clcrVisitStatus')).not.toContainText('Zapisano');
  await page.locator('#clcrOpenHistoryBtn').click();
  await expect(page.locator('#clcrPatientCard .vilda-clcr-history')).toContainText('Brak zapisanych obliczeń');
});

test('a conflict or deleted note never turns a stale editor into an upsert', async ({ page }) => {
  await openCalculator(page);
  await applyAcr(page, '45');
  const [note] = await saveVisible(page);
  await page.locator('#clcrOpenBadaniaBtn').click();
  await openDetails(page, note.id);
  await edit(page);
  await field(page, 'U_Alb').fill('13.6');
  await configureMemory(page, { rejectUpdate: 'conflict' });
  await page.locator('#saveEditedMeasurement').click();
  await expect(page.locator('#editError')).toBeVisible();
  expect((await memory(page)).notes).toEqual([note]);
  await configureMemory(page, { rejectUpdate: null });
  await page.evaluate(id => window.__clcrRecordFixture.removeExternally(id), note.id);
  if (await page.locator('#editDialog').isVisible()) {
    await page.locator('#saveEditedMeasurement').click();
    await expect(page.locator('#editError')).toBeVisible();
  }
  expect((await memory(page)).notes).toHaveLength(0);
  expect((await memory(page)).saves).toHaveLength(1);
  expect((await memory(page)).originalsLocked).toBe(true);
});
